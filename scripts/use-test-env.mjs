#!/usr/bin/env node
/**
 * Copy .env.test → .env.local for local/test work against heyklever Supabase.
 * Preserves any existing SUPABASE_SERVICE_ROLE_KEY / secrets already in .env.local.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const testPath = path.join(root, '.env.test');
const localPath = path.join(root, '.env.local');

if (!fs.existsSync(testPath)) {
  console.error('Missing .env.test');
  process.exit(1);
}

const testEnv = fs.readFileSync(testPath, 'utf8');
const existing = fs.existsSync(localPath) ? fs.readFileSync(localPath, 'utf8') : '';

function parse(envText) {
  const map = new Map();
  for (const line of envText.split(/\r?\n/)) {
    if (!line || line.trimStart().startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i === -1) continue;
    map.set(line.slice(0, i).trim(), line.slice(i + 1));
  }
  return map;
}

const next = parse(testEnv);
const prev = parse(existing);

// Keep secrets from existing .env.local when test file leaves them blank/commented.
for (const key of [
  'SUPABASE_SERVICE_ROLE_KEY',
  'CRON_SECRET',
  'SMTP_HOST',
  'SMTP_PORT',
  'SMTP_USER',
  'SMTP_PASS',
  'SMTP_FROM',
  'N8N_AI_SUMMARY_WEBHOOK_URL',
  'N8N_DOCUMENT_EMBEDDINGS_WEBHOOK_URL',
  'N8N_FORUM_PROMPTS_WEBHOOK_URL',
  'N8N_FORUM_SYNTHESIS_WEBHOOK_URL',
  'N8N_FORUM_RSS_WEBHOOK_URL',
  'N8N_FORUM_SAK_PROMPTS_WEBHOOK_URL',
  'FORUM_ADMIN_EMAILS',
]) {
  if ((!next.has(key) || !next.get(key)) && prev.has(key) && prev.get(key)) {
    next.set(key, prev.get(key));
  }
}

const lines = [
  '# Generated by npm run env:test from .env.test',
  '# Secrets preserved from previous .env.local when present.',
  '',
];
for (const [k, v] of next) {
  lines.push(`${k}=${v}`);
}
lines.push('');

fs.writeFileSync(localPath, lines.join('\n'));
console.log(`Wrote ${localPath} (Supabase → ${next.get('NEXT_PUBLIC_SUPABASE_URL')})`);
